const assert=require('node:assert/strict');const {methods:m}=require('../assets/tool-math.js');
const near=(a,b)=>assert.ok(Math.abs(a-b)<1e-8,`${a} != ${b}`);
near(m.position({balance:5000,risk:1,stop:25,pipValue:10,step:.01})['Lots (rounded down)'],.2);
near(m.position({balance:1,risk:1,stop:25,pipValue:10,step:.01})['Lots (rounded down)'],0);
near(m.pip({units:10000,pip:.0001,rate:1})['Pip value (account currency)'],1);
near(m.pip({units:10000,pip:.01,rate:.0065})['Pip value (account currency)'],.65);
near(m.gain({start:100,end:80})['Recovery needed (%)'],25);
assert.equal(m.gain({start:100,end:0})['Recovery needed (%)'],'No finite recovery');
assert.deepEqual(m.pivot({high:110,low:90,close:100}),{Pivot:100,R1:110,S1:90,R2:120,S2:80,R3:130,S3:70});
assert.throws(()=>m.pivot({high:90,low:110,close:100}));
near(m.expectancy({winRate:40,win:2,loss:1,cost:.1})['Expected net outcome per trade'],.1);
near(m.reward({entry:100,stop:110,target:80})['Reward / risk'],2);
assert.equal(m.reward({entry:100,stop:110,target:80}).Direction,'Short');
assert.throws(()=>m.reward({entry:100,stop:100,target:120}));
assert.throws(()=>m.reward({entry:100,stop:90,target:80}));
near(m.correlation({a:'100,102,101,104,103',b:'200,204,202,208,206'})['Return correlation'],1);
assert.throws(()=>m.correlation({a:'100,100,100,100',b:'100,101,102,103'}));
assert.throws(()=>m.correlation({a:'100,102,101,104',b:'200,204,202,208,206'}));
assert.throws(()=>m.volatility({prices:'100,0,101,104',periods:252}));
near(m.volatility({prices:'100,100,100,100',periods:252})['Annualized volatility (%)'],0);
assert.equal(m.sentiment({equity:1,aud:1,vix:-1,credit:-1})['Checklist score (−4 to +4)'],4);
console.log('PASS: numerical cases, loss recovery, rounding, short trades, invalid inputs, correlation and volatility.');
